const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const base = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(base, 'public/index.html'), 'utf8');
const data = JSON.parse(html.match(/<script id="benchmark-data" type="application\/json">([\s\S]*?)<\/script>/)[1]);
const script = html.match(/<script>\s*([\s\S]*?)<\/script>/)[1];
const ids = ['benchmark-data','snapshot','model-filter','effort-filter','bar-max','bars','bar-labels','scatter-max','scatter-axis','scatter','table-head','table-body','detail'];
const elements = Object.fromEntries(ids.map(id => [id, { innerHTML:'', textContent:'', value:id==='model-filter'?'all':'', options:[], events:{}, add(o){this.options.push(o)}, addEventListener(k,fn){this.events[k]=fn}, focus(){this.focused=true}, scrollIntoView(){} }]));
elements['benchmark-data'].textContent = JSON.stringify(data);
const events = {};
const document = {getElementById:id=>elements[id], addEventListener:(k,fn)=>{events[k]=fn}};
const ctx = {document, globalThis:{}, Option:function(text,value){return {text,value}}, matchMedia:()=>({matches:true})};
vm.runInNewContext(script,ctx);
assert.match(elements.snapshot.innerHTML, /Snapshot generated/);
assert.equal(elements['model-filter'].options.length,5);
assert.equal(elements['effort-filter'].options.length,5);
assert.match(elements.bars.innerHTML, /aria-label="gpt-6-astra High Fast/);
assert.match(elements.scatter.innerHTML, /role="button"/);
assert.match(elements['table-body'].innerHTML, /n=3/);
const expected=ctx.globalThis.LLMBenchCore.aggregate(data.results,'gpt-6-astra','high','fast');
assert.equal(expected.response.toFixed(2),"46.42");
assert.match(elements['table-body'].innerHTML, /46\.42/);
elements['model-filter'].value='gpt-6-astra'; elements['model-filter'].events.change();
assert.doesNotMatch(elements['table-body'].innerHTML,/gpt-6-luna/);
elements['effort-filter'].value='low'; elements['effort-filter'].events.change();
assert.match(elements.bars.innerHTML,/gpt-6-astra Low Fast/);
events.click({target:{closest:()=>({dataset:{model:'gpt-6-astra',effort:'low'}})}});
assert.match(elements.detail.innerHTML,/gpt-6-astra · Low/);
assert.match(elements.detail.innerHTML,/Included in mean/);
assert.match(elements.detail.innerHTML,/reconcile/);
assert.match(elements.detail.innerHTML,/Benchmark run/);
assert.equal(elements.detail.focused,true);
console.log('Rendering and interaction logic tests passed');
